"""Generates audio/<key>.mp3 for every text in tools/tts.json that is new or changed,
then writes data/durations.js. Needs: pip install edge-tts, and ffmpeg on PATH."""
import asyncio, hashlib, json, subprocess, sys, tempfile
from pathlib import Path
import edge_tts

ROOT = Path(__file__).resolve().parent.parent
VOICES = {'lv': ('lv-LV-EveritaNeural', '-8%'), 'el': ('el-GR-AthinaNeural', '-10%')}
items = json.loads((ROOT / 'tools/tts.json').read_text(encoding='utf-8'))
hashes_file = ROOT / 'tools/tts-hashes.json'
hashes = json.loads(hashes_file.read_text()) if hashes_file.exists() else {}

def digest(it):
    return hashlib.sha1((it['voice'] + VOICES[it['voice']][1] + it['text']).encode()).hexdigest()

async def make(key, it, sem):
    out = ROOT / 'audio' / f'{key}.mp3'
    if hashes.get(key) == digest(it) and out.exists():
        return
    async with sem:
        out.parent.mkdir(parents=True, exist_ok=True)
        voice, rate = VOICES[it['voice']]
        with tempfile.TemporaryDirectory() as tmp:
            raw = Path(tmp) / 'raw.mp3'
            for attempt in range(8):
                try:
                    await edge_tts.Communicate(it['text'], voice, rate=rate).save(str(raw))
                    if raw.stat().st_size > 0:
                        break
                except Exception:
                    pass
                await asyncio.sleep(2 + attempt * 2)
            else:
                print('FAILED', key)
                return
            subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', str(raw), '-ac', '1', '-ar', '24000', '-b:a', '32k', str(out)], check=True)
        hashes[key] = digest(it)
        hashes_file.write_text(json.dumps(hashes, indent=1, sort_keys=True))
        print('made', key)

async def main():
    sem = asyncio.Semaphore(2)
    await asyncio.gather(*(make(k, it, sem) for k, it in items.items()))
    hashes_file.write_text(json.dumps(hashes, indent=1, sort_keys=True))
    dur = {}
    for k in items:
        f = ROOT / 'audio' / f'{k}.mp3'
        if f.exists():
            s = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(f)], capture_output=True, text=True).stdout
            dur[k] = round(float(s))
    (ROOT / 'data/durations.js').write_text('// Generated by tools/gen_audio.py\nexport const DUR = ' + json.dumps(dur, sort_keys=True) + ';\n')
    print(len(dur), 'clips')

asyncio.run(main())
