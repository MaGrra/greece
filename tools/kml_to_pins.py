"""Snapshot the shared Google My Maps into data/mymap.js (used when the backend is unreachable).
Usage: python3 tools/kml_to_pins.py [path/to/map.kml]   (downloads the map when no file is given)"""
import json, sys, urllib.request, xml.etree.ElementTree as ET
from pathlib import Path

MID = '1V9nXn0qyupGXmL1IGmQECzKKDhrxlg4'
root = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urllib.request.urlopen(
    f'https://www.google.com/maps/d/kml?forcekml=1&mid={MID}', timeout=30).read()
ns = {'k': 'http://www.opengis.net/kml/2.2'}
pins = []
for pm in ET.fromstring(src).iter('{http://www.opengis.net/kml/2.2}Placemark'):
    c = pm.findtext('.//k:Point/k:coordinates', '', ns).strip()
    if not c:
        continue
    lng, lat = map(float, c.split(',')[:2])
    pins.append({'name': pm.findtext('k:name', '', ns).strip(), 'note': (pm.findtext('k:description', '', ns) or '').strip(), 'lat': lat, 'lng': lng})
(root / 'data' / 'mymap.js').write_text('// Generated by tools/kml_to_pins.py. Live pins come from the backend.\nexport const MYMAP_SNAPSHOT = ' + json.dumps(pins, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')
print(len(pins), 'pins')
